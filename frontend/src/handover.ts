/**
 * Clinician handover note: a fixed template filled from the twin record, state, forecast and (optionally) the AGP
 * summary. No language model, no free text: the same inputs always give the same note.
 *
 * The grounding check is independent of the template. It re-parses the finished text, extracts every number,
 * and looks each one up in a table built directly from the raw inputs (`groundingFacts`). A number passes only if
 * it is one of those values (at 0, 1 or 2 decimals, or as a percentage of a probability), or one of the few stated
 * definition constants (thresholds and windows), AND that value belongs to a field the line describes (a forecast
 * line may only use forecast fields, and so on; see LINE_SCOPES). Any other number is reported as untraced.
 * Limits: a swap between two in-scope values on the same line is not detected, and the check shows only that the
 * note copies its inputs faithfully; it says nothing about whether the forecast is accurate.
 *
 * The note describes; it never instructs. Synthetic data, research prototype, not a diagnosis.
 * Self-contained (type-only imports) so the Node test runner can load it directly.
 */
import type { AgpSummary, Forecast, Medication, TwinCurveEstimate, TwinState } from "./api/types";

export interface HandoverInput {
  record: { patient_id: string; display_name: string; age_years: number; diabetes_duration_years: number;
            utc_offset_minutes: number; medications: Medication[] };
  state: TwinState;
  forecast: Forecast | null;
  agp?: AgpSummary | null;
}

/** Thresholds and windows written into the template itself (not patient data). */
export const DEFINITIONS: Record<string, string> = {
  "70": "low-glucose threshold, mg/dL (international consensus)",
  "180": "upper limit of the 70-180 mg/dL target range",
  "3": "CGM completeness window, hours",
};

export const HANDOVER_FOOTER = "Generated by a fixed template from the twin's own record, state and forecast; synthetic data; " +
  "research prototype. Describes model output only: not a diagnosis, not a treatment instruction.";

const TREND: Record<string, string> = {
  rising_fast: "rising fast", rising: "rising", stable: "stable", falling: "falling", falling_fast: "falling fast", unknown: "trend unavailable",
};

const hhmm = (iso: string, offsetMin: number) => {
  const d = new Date(new Date(iso).getTime() + offsetMin * 60_000);
  return `${String(d.getUTCHours()).padStart(2, "0")}:${String(d.getUTCMinutes()).padStart(2, "0")}`;
};
const utcOffset = (m: number) => `UTC${m >= 0 ? "+" : "-"}${String(Math.floor(Math.abs(m) / 60)).padStart(2, "0")}:${String(Math.abs(m) % 60).padStart(2, "0")}`;
const r0 = (v: number) => String(Math.round(v));
const r1 = (v: number) => v.toFixed(1);
const signed1 = (v: number) => `${v < 0 ? "−" : "+"}${Math.abs(v).toFixed(1)}`;
const pctOf = (p: number) => `${Math.round(p * 100)}%`;

/** The note, one line per item. */
export function buildHandover(inp: HandoverInput): string[] {
  const { record: rec, state: st, forecast: fc, agp } = inp;
  const off = rec.utc_offset_minutes;
  const lines: string[] = [];
  lines.push(`Handover: ${rec.display_name}, ${rec.patient_id}; ${rec.age_years} y; diabetes duration ${rec.diabetes_duration_years} y. ` +
    `Twin state at ${hhmm(st.as_of, off)} local time (${utcOffset(off)}).`);

  const g = st.last_glucose_mg_dl;
  const trend = st.glucose_trend_mg_dl_per_min;
  const dq = st.data_quality;
  lines.push(`Latest CGM: ${g == null ? "no reading" : `${r0(g)} mg/dL`}, ${TREND[st.trend_arrow] ?? "trend unavailable"}` +
    `${trend == null ? "" : ` (${signed1(trend)} mg/dL/min)`}. ` +
    `${dq.minutes_since_last_cgm == null ? "No CGM received yet" : `Last reading ${r0(dq.minutes_since_last_cgm)} min ago`}; ` +
    `CGM completeness over 3 h ${pctOf(dq.cgm_completeness_3h)}${dq.stale ? "; data STALE" : ""}.`);

  const s = st.summary_24h;
  if (s.n_readings > 0 && s.mean_mg_dl != null) {
    lines.push(`Past ${r0(s.window_hours)} h (${s.n_readings} readings): mean ${r0(s.mean_mg_dl)} mg/dL; ` +
      `time in 70-180 range ${s.time_in_range_pct == null ? "n/a" : `${r0(s.time_in_range_pct)}%`}, ` +
      `above ${s.time_above_range_pct == null ? "n/a" : `${r0(s.time_above_range_pct)}%`}, ` +
      `below ${s.time_below_range_pct == null ? "n/a" : `${r0(s.time_below_range_pct)}%`}.`);
  }

  if (fc && fc.status === "ok" && fc.trajectory.length) {
    const pts = fc.trajectory.filter((p) => [30, 60, 120].includes(p.horizon_min));
    const last = fc.trajectory[fc.trajectory.length - 1];
    lines.push(`Model forecast (synthetic-trained, not validated on real patients): ` +
      pts.map((p) => `+${p.horizon_min} min ${r0(p.glucose_mg_dl)}`).join(", ") + ` mg/dL; ` +
      `${r0(fc.interval_level * 100)}% prediction interval at +${last.horizon_min} min ${r0(last.lower_mg_dl)}-${r0(last.upper_mg_dl)} mg/dL.`);
    const ex = fc.excursion;
    if (ex) {
      lines.push(`Estimated risk of glucose above 180 mg/dL within ${ex.horizon_min} min: ${pctOf(ex.probability)} ` +
        `(${ex.risk_band} band; alert threshold ${pctOf(ex.alert_threshold)}; ${ex.alert ? "ALERT raised" : "no alert"}).`);
    }
    const low = fc.trajectory.filter((p) => p.horizon_min >= 30 && p.lower_mg_dl < 70);
    lines.push(low.length
      ? `Low watch: the lower edge of the prediction interval falls below 70 mg/dL from +${low[0].horizon_min} min (an interval edge, not a probability).`
      : `Low watch: the lower edge of the prediction interval stays at or above 70 mg/dL (not a guarantee).`);
  } else {
    lines.push(`Model forecast: withheld${fc?.reason ? ` (${fc.reason})` : ""}.`);
  }

  lines.push(`Context: carbs on board ${r0(st.carbs_on_board_g)} g; ` +
    `${st.minutes_since_last_meal == null ? "no meal logged" : `last logged meal ${r0(st.minutes_since_last_meal)} min ago`}; ` +
    `${r0(st.steps_last_60min)} steps in the past hour; personal carb sensitivity ` +
    `${st.personal.carb_sensitivity_mg_dl_per_g.toFixed(2)} mg/dL per g from ${st.personal.meals_used} meals.`);

  if (agp && agp.n_readings > 0) {
    lines.push(`Glucose profile (${agp.window_days}-day window, as of ${hhmm(agp.as_of, off)}): ${r1(agp.days_with_data)} days of data, ` +
      `coverage ${r1(agp.coverage_pct)}%${agp.sufficient ? "" : " (below the 14-day / 70% consensus minimum)"}; ` +
      `time in range ${agp.tir_70_180_pct == null ? "n/a" : `${r1(agp.tir_70_180_pct)}%`}; ` +
      `GMI ${agp.gmi_pct == null ? "n/a" : `${r1(agp.gmi_pct)}%`} (estimate from mean glucose, not a laboratory result).`);
  }

  if (rec.medications.length) {
    lines.push(`Medications on record: ${rec.medications.map((m) => `${m.name}${m.dose ? ` ${m.dose}` : ""}`).join("; ")}.`);
  }
  lines.push(HANDOVER_FOOTER);
  return lines;
}

/** Every number the note may contain, keyed by its rendered form, with where it comes from. */
export type Facts = Map<string, string[]>;

export function groundingFacts(inp: HandoverInput): Facts {
  const facts: Facts = new Map();
  const put = (t: string, src: string) => { const l = facts.get(t) ?? []; if (!l.includes(src)) l.push(src); facts.set(t, l); };
  const add = (v: number | null | undefined, src: string) => {
    if (v == null || !Number.isFinite(v)) return;
    for (const x of [v, Math.abs(v)]) for (const t of [Math.round(x).toString(), x.toFixed(1), x.toFixed(2)]) put(t, src);
  };
  const addProb = (p: number | null | undefined, src: string) => { if (p != null) add(Math.round(p * 100), src); };
  const addTokens = (text: string, src: string) => { for (const t of numberTokens(text)) put(t, src); };
  const { record: rec, state: st, forecast: fc, agp } = inp;

  addTokens(rec.patient_id, "record.patient_id");
  addTokens(rec.display_name, "record.display_name");
  add(rec.age_years, "record.age_years");
  add(rec.diabetes_duration_years, "record.diabetes_duration_years");
  addTokens(hhmm(st.as_of, rec.utc_offset_minutes), "state.as_of");
  addTokens(utcOffset(rec.utc_offset_minutes), "record.utc_offset_minutes");
  rec.medications.forEach((m, i) => addTokens(`${m.name} ${m.dose ?? ""}`, `record.medications[${i}]`));

  add(st.last_glucose_mg_dl, "state.last_glucose_mg_dl");
  add(st.glucose_trend_mg_dl_per_min, "state.glucose_trend_mg_dl_per_min");
  add(st.data_quality.minutes_since_last_cgm, "state.data_quality.minutes_since_last_cgm");
  addProb(st.data_quality.cgm_completeness_3h, "state.data_quality.cgm_completeness_3h");
  const s = st.summary_24h;
  add(s.window_hours, "state.summary_24h.window_hours");
  add(s.n_readings, "state.summary_24h.n_readings");
  add(s.mean_mg_dl, "state.summary_24h.mean_mg_dl");
  add(s.time_in_range_pct, "state.summary_24h.time_in_range_pct");
  add(s.time_above_range_pct, "state.summary_24h.time_above_range_pct");
  add(s.time_below_range_pct, "state.summary_24h.time_below_range_pct");
  add(st.carbs_on_board_g, "state.carbs_on_board_g");
  add(st.minutes_since_last_meal, "state.minutes_since_last_meal");
  add(st.steps_last_60min, "state.steps_last_60min");
  add(st.personal.carb_sensitivity_mg_dl_per_g, "state.personal.carb_sensitivity_mg_dl_per_g");
  add(st.personal.meals_used, "state.personal.meals_used");

  if (fc) {
    addProb(fc.interval_level, "forecast.interval_level");
    fc.trajectory.forEach((p, i) => {
      add(p.horizon_min, `forecast.trajectory[${i}].horizon_min`);
      add(p.glucose_mg_dl, `forecast.trajectory[${i}].glucose_mg_dl`);
      add(p.lower_mg_dl, `forecast.trajectory[${i}].lower_mg_dl`);
      add(p.upper_mg_dl, `forecast.trajectory[${i}].upper_mg_dl`);
    });
    if (fc.excursion) {
      add(fc.excursion.horizon_min, "forecast.excursion.horizon_min");
      addProb(fc.excursion.probability, "forecast.excursion.probability");
      addProb(fc.excursion.alert_threshold, "forecast.excursion.alert_threshold");
    }
    if (fc.reason) addTokens(fc.reason, "forecast.reason");
  }
  if (agp) {
    add(agp.window_days, "agp.window_days");
    addTokens(hhmm(agp.as_of, rec.utc_offset_minutes), "agp.as_of");
    add(agp.days_with_data, "agp.days_with_data");
    add(agp.coverage_pct, "agp.coverage_pct");
    add(agp.tir_70_180_pct, "agp.tir_70_180_pct");
    add(agp.gmi_pct, "agp.gmi_pct");
    add(14, "agp sufficiency rule (14 days)");
  }
  for (const [k, v] of Object.entries(DEFINITIONS)) put(k, `definition: ${v}`);
  return facts;
}

/** Which input fields each line of the note may draw numbers from (matched by the line's opening words). */
export const LINE_SCOPES: [string, string[]][] = [
  ["Handover:", ["record.patient_id", "record.display_name", "record.age_years", "record.diabetes_duration_years", "state.as_of", "record.utc_offset_minutes"]],
  ["Latest CGM:", ["state.last_glucose_mg_dl", "state.glucose_trend_mg_dl_per_min", "state.data_quality.", "definition:"]],
  ["Past ", ["state.summary_24h.", "definition:"]],
  ["Model forecast", ["forecast.trajectory", "forecast.interval_level", "forecast.reason"]],
  ["Estimated risk", ["forecast.excursion.", "definition:"]],
  ["Low watch:", ["forecast.trajectory", "definition:"]],
  ["Context:", ["state.carbs_on_board_g", "state.minutes_since_last_meal", "state.steps_last_60min", "state.personal."]],
  ["Glucose profile", ["agp", "definition:"]],
  ["Medications on record:", ["record.medications"]],
  ["Generated by", []],
];

/** Numbers as written: clock times (07:55) stay whole; "70-180" yields 70 and 180; a leading sign is ignored. */
export function numberTokens(text: string): string[] {
  return text.match(/\d{1,2}:\d{2}|\d+(?:\.\d+)?/g) ?? [];
}

export interface GroundingReport {
  total: number; traced: number; fromData: number; fromDefinitions: number;
  untraced: string[]; sources: { token: string; source: string }[];
}

export function verifyGrounding(text: string, facts: Facts, scopes: [string, string[]][] = LINE_SCOPES): GroundingReport {
  const sources: { token: string; source: string }[] = [];
  const untraced: string[] = [];
  for (const line of text.split("\n")) {
    const scope = scopes.find(([prefix]) => line.startsWith(prefix))?.[1] ?? []; // unknown line: nothing allowed
    for (const t of numberTokens(line)) {
      const src = (facts.get(t) ?? []).find((s) => scope.some((sc) => s.startsWith(sc)));
      if (src) sources.push({ token: t, source: src });
      else untraced.push(t);
    }
  }
  const fromDefinitions = sources.filter((s) => s.source.startsWith("definition:")).length;
  return { total: sources.length + untraced.length, traced: sources.length, fromData: sources.length - fromDefinitions,
           fromDefinitions, untraced, sources };
}

export function groundingLabel(r: GroundingReport): string {
  if (r.total === 0) return "No numbers to check.";
  const p = Math.round((100 * r.traced) / r.total);
  return r.untraced.length === 0
    ? `Verified: ${p}% of numbers (${r.traced}/${r.total}) trace to the twin record, state or forecast (${r.fromData}) or a stated definition (${r.fromDefinitions}).`
    : `NOT verified: ${r.untraced.length} of ${r.total} numbers do not trace to the inputs (${r.untraced.join(", ")}). Do not use this note.`;
}

/* ------------------------------------------------------------------------------------------------------------- *
 * Atithi (patient) plain-language companion summary.
 *
 * Happiest Health calls the people it serves "atithis" (guests) and describes "more educating than medicating"
 * (Ashok Soota, PTI, Oct 2025). This is the same fixed-template idea in patient language, checked by the SAME
 * verifier (`verifyGrounding`) with its own line scopes: if any number does not trace, the card refuses to render.
 * It explains model output; it never tells anyone to change a medicine, insulin or any treatment.
 * ------------------------------------------------------------------------------------------------------------- */

/** The meal being considered in the What-If table (its research twin-curve estimate) and the top-ranked swap. */
export interface CompanionInput extends HandoverInput {
  scenario?: { grams: number; dish: string | null; twin: TwinCurveEstimate } | null;
  swap?: { grams: number; dish: string; rise120: number } | null;
}

/** Constants written into the companion template (not patient data). */
export const COMPANION_DEFINITIONS: Record<string, string> = {
  "2": "outlook window, hours (the forecast runs to +120 min)",
};

export const COMPANION_SECTIONS = [
  "Your glucose now and over the next 2 hours",
  "What your digital twin learned about your meals",
  "A gentle option to discuss with your doctor",
] as const;

export const COMPANION_FOOTER = "About this note: an educational simulation from synthetic data, written by a fixed template. " +
  "It is not a diagnosis and it does not change any medicine or treatment; please talk to your doctor before changing anything.";

const ARROW_PLAIN: Record<string, string> = {
  rising_fast: "going up quickly", rising: "going up slowly", stable: "steady", falling: "going down slowly",
  falling_fast: "going down quickly", unknown: "without a clear direction yet",
};

/** One entry per section; each line starts with a scoped prefix ("Right now:", "Outlook:", ...). */
export function buildCompanion(inp: CompanionInput): { section: string; lines: string[] }[] {
  const { state: st, forecast: fc, scenario, swap } = inp;
  const now: string[] = [];
  const g = st.last_glucose_mg_dl;
  const dq = st.data_quality;
  now.push(g == null
    ? "Right now: the twin has not received a glucose reading yet."
    : `Right now: your latest glucose reading is ${r0(g)} mg/dL and it is ${ARROW_PLAIN[st.trend_arrow] ?? ARROW_PLAIN.unknown}.` +
      (dq.stale && dq.minutes_since_last_cgm != null ? ` It was taken ${r0(dq.minutes_since_last_cgm)} minutes ago, so it may be out of date.` : ""));
  const last = fc && fc.status === "ok" && fc.trajectory.length ? fc.trajectory[fc.trajectory.length - 1] : null;
  if (fc && last) {
    let tail: string;
    if (last.lower_mg_dl < 70) tail = " The lower end dips under 70 mg/dL, which your care team can explain and help you watch for.";
    else if (fc.excursion?.alert || last.upper_mg_dl > 180) tail = " The upper end goes above 180 mg/dL, which is worth looking at together with your care team.";
    else tail = " That whole range stays inside the 70-180 mg/dL target range.";
    now.push(`Outlook: in about 2 hours the twin's best guess is around ${r0(last.glucose_mg_dl)} mg/dL; it could reasonably be ` +
      `anywhere from ${r0(last.lower_mg_dl)} to ${r0(last.upper_mg_dl)} mg/dL (its ${r0(fc.interval_level * 100)}% range).${tail}`);
  } else {
    now.push("Outlook: the twin is not making a forecast at the moment, usually because recent readings are missing.");
  }

  const meals: string[] = [];
  const p = st.personal;
  meals.push(p.meals_used > 0
    ? `Your meals: from ${p.meals_used} of your logged meals, the twin learned that each gram of carbohydrate tends to raise your ` +
      `glucose by about ${p.carb_sensitivity_mg_dl_per_g.toFixed(1)} mg/dL. This is an average, not an exact rule.`
    : "Your meals: the twin has not seen enough of your logged meals yet, so it uses a typical value for now.");
  const mins = st.minutes_since_last_meal;
  if (mins == null) meals.push("Recent meal: no meal has been logged yet.");
  else {
    const when = mins < 120 ? `${r0(mins)} minutes ago` : `about ${r0(mins / 60)} hours ago`;
    meals.push(`Recent meal: your last logged meal was ${when}` + (st.carbs_on_board_g >= 1
      ? `, and about ${r0(st.carbs_on_board_g)} g of its carbohydrate is still being absorbed.`
      : ", and the twin thinks it has been fully absorbed."));
  }

  const discuss: string[] = [];
  if (scenario) {
    const t = scenario.twin;
    const name = scenario.dish ? `${scenario.dish} (about ${scenario.grams} g of carbohydrate)` : `a meal with ${scenario.grams} g of carbohydrate`;
    const walk = t.with_walk_delta_glucose_mg_dl?.["120"];
    discuss.push(`To discuss: in the twin's simulation, ${name} is followed by a rise of about ${r0(t.delta_glucose_mg_dl["120"])} mg/dL ` +
      `after 2 hours` + (walk != null
        ? `; with an easy ${t.walk.minutes}-minute walk after it (about ${t.walk.steps} steps) the simulated rise is about ${r0(walk)} mg/dL.`
        : "."));
    if (swap) discuss.push(`Lower-carbohydrate option the twin ranked first: ${swap.dish} (about ${swap.grams} g), simulated rise about ${r0(swap.rise120)} mg/dL after 2 hours.`);
  } else {
    discuss.push("To discuss: your care team can use the twin's What-If comparison to show how a meal, or a short walk after it, might change your glucose.");
  }
  discuss.push(COMPANION_FOOTER);
  return [
    { section: COMPANION_SECTIONS[0], lines: now },
    { section: COMPANION_SECTIONS[1], lines: meals },
    { section: COMPANION_SECTIONS[2], lines: discuss },
  ];
}

/** Handover facts plus the What-If scenario, the ranked swap, one derived value and the companion constants. */
export function companionFacts(inp: CompanionInput): Facts {
  const facts = groundingFacts(inp);
  const put = (t: string, src: string) => { const l = facts.get(t) ?? []; if (!l.includes(src)) l.push(src); facts.set(t, l); };
  const add = (v: number | null | undefined, src: string) => {
    if (v == null || !Number.isFinite(v)) return;
    for (const x of [v, Math.abs(v)]) for (const t of [Math.round(x).toString(), x.toFixed(1), x.toFixed(2)]) put(t, src);
  };
  const { state: st, scenario, swap } = inp;
  if (st.minutes_since_last_meal != null) add(Math.round(st.minutes_since_last_meal / 60), "state.minutes_since_last_meal (in hours)");
  if (scenario) {
    add(scenario.grams, "scenario.grams");
    if (scenario.dish) for (const t of numberTokens(scenario.dish)) put(t, "scenario.dish");
    add(scenario.twin.delta_glucose_mg_dl["120"], "scenario.twin_curve.delta_120");
    add(scenario.twin.with_walk_delta_glucose_mg_dl?.["120"], "scenario.twin_curve.with_walk_delta_120");
    add(scenario.twin.walk.minutes, "scenario.twin_curve.walk.minutes");
    add(scenario.twin.walk.steps, "scenario.twin_curve.walk.steps");
  }
  if (swap) {
    add(swap.grams, "swap.grams");
    for (const t of numberTokens(swap.dish)) put(t, "swap.dish");
    add(swap.rise120, "swap.twin_curve.delta_120");
  }
  for (const [k, v] of Object.entries(COMPANION_DEFINITIONS)) put(k, `definition: ${v}`);
  return facts;
}

export const COMPANION_SCOPES: [string, string[]][] = [
  ["Right now:", ["state.last_glucose_mg_dl", "state.data_quality.minutes_since_last_cgm"]],
  ["Outlook:", ["forecast.trajectory", "forecast.interval_level", "definition:"]],
  ["Your meals:", ["state.personal."]],
  ["Recent meal:", ["state.minutes_since_last_meal", "state.carbs_on_board_g"]],
  ["To discuss:", ["scenario.", "definition:"]],
  ["Lower-carbohydrate option", ["swap.", "definition:"]],
  ["About this note:", []],
  ["Your glucose now", ["definition:"]],
  ["What your digital twin", []],
  ["A gentle option", []],
];

/** Text the verifier reads: every section title and every line. */
export function companionText(sections: { section: string; lines: string[] }[]): string {
  return sections.flatMap((s) => [s.section, ...s.lines]).join("\n");
}
