"""Deterministic FHIR R4 (4.0.1) export of one SYNTHETIC patient: an interoperability prototype.

Output is a ``collection`` Bundle with Patient, Condition, MedicationStatement and Observation resources,
plus (when a forecast is supplied) one RiskAssessment: the model's 2-hour excursion probability as
``probabilityDecimal`` and, if the lower edge of the 80% prediction interval falls below 70 mg/dL, a
qualitative low-glucose watch with NO probability attached (a conformal lower bound is not a probability).
It is checked against the R4 resource structure (scripts/validate_fhir_export.py) and uses only codes looked
up in the source terminologies:

* LOINC 99504-3 (glucose, interstitial fluid, mass/volume; the CGM code), 4548-4 (HbA1c), 1558-6 (fasting
  glucose, serum/plasma).
* SNOMED CT 44054006 (type 2 diabetes), 59621000 (essential hypertension), 370992007 (dyslipidaemia).
* RxNorm ingredient RxCUIs from RxNav.

Labs without a verified code (eGFR, LDL) are exported with display text only. Nothing here is certified,
profiled against national implementation guides (e.g. ABDM / NRCeS), or a claim of compliance. Every
resource carries a ``synthetic`` meta tag. Identifiers are UUIDv5 values derived from the patient ID, and
the export time is the last observation it includes, so the same record and history always give the same
Bundle.
"""

from __future__ import annotations

import uuid
from collections.abc import Iterable
from datetime import datetime, timedelta
from typing import Any

from glucotwin.contracts import Forecast, PatientRecord

FHIR_VERSION = "4.0.1"
REPO_URL = "https://github.com/mohnishshanmugavadivel1-dotcom/digital-twin-healthcare-agent"
LOINC = "http://loinc.org"
SNOMED = "http://snomed.info/sct"
RXNORM = "http://www.nlm.nih.gov/research/umls/rxnorm"
UCUM = "http://unitsofmeasure.org"
OBS_CATEGORY = "http://terminology.hl7.org/CodeSystem/observation-category"
COND_CLINICAL = "http://terminology.hl7.org/CodeSystem/condition-clinical"
COND_CATEGORY = "http://terminology.hl7.org/CodeSystem/condition-category"

CGM_CODE = ("99504-3", "Glucose [Mass/volume] in Interstitial fluid")
LAB_CODES: dict[str, tuple[str, str]] = {
    "HbA1c": ("4548-4", "Hemoglobin A1c/Hemoglobin.total in Blood"),
    "Fasting plasma glucose": ("1558-6", "Fasting glucose [Mass/volume] in Serum or Plasma"),
}
UCUM_UNITS = {"%": "%", "mg/dL": "mg/dL", "mL/min/1.73m2": "mL/min/{1.73_m2}"}
CONDITION_CODES: dict[str, tuple[str, str]] = {
    "Type 2 diabetes mellitus": ("44054006", "Diabetes mellitus type 2 (disorder)"),
    "Essential hypertension": ("59621000", "Essential hypertension (disorder)"),
    "Dyslipidaemia": ("370992007", "Dyslipidemia (disorder)"),
}
RXNORM_CODES: dict[str, tuple[str, str]] = {
    "Metformin": ("6809", "metformin"),
    "Glimepiride": ("25789", "glimepiride"),
    "Sitagliptin": ("593411", "sitagliptin"),
    "Insulin glargine": ("274783", "insulin glargine"),
    "Ramipril": ("35296", "ramipril"),
    "Atorvastatin": ("83367", "atorvastatin"),
}
SYNTHETIC_TAG = {"system": f"{REPO_URL}/fhir/tags", "code": "synthetic",
                 "display": "Synthetic patient generated by GlucoTwin; not a real person"}
DISCLAIMER = ("Interoperability prototype: deterministic FHIR R4 export of a synthetic patient. Not certified, not "
              "profiled against ABDM/NRCeS guides, not a compliance claim, not for clinical use.")


def _uid(pid: str, key: str) -> str:
    return f"urn:uuid:{uuid.uuid5(uuid.NAMESPACE_URL, f'{REPO_URL}/{pid}/{key}')}"


def _iso(ts: datetime) -> str:
    if ts.tzinfo is None:
        raise ValueError("FHIR dateTime values must carry a timezone")
    return ts.isoformat()


def _meta() -> dict[str, Any]:
    return {"tag": [dict(SYNTHETIC_TAG)]}


def _coding(system: str, code: str, display: str) -> dict[str, Any]:
    return {"system": system, "code": code, "display": display}


def _quantity(value: float, unit: str) -> dict[str, Any]:
    q: dict[str, Any] = {"value": value, "unit": unit}
    if unit in UCUM_UNITS:
        q |= {"system": UCUM, "code": UCUM_UNITS[unit]}
    return q


LOW_GLUCOSE_MG_DL = 70.0
HYPO_DRUG_CLASSES = {"sulfonylurea": "sulfonylurea", "basal_insulin": "basal insulin"}


def _risk_assessment(record: PatientRecord, fc: Forecast | None, subject: dict[str, Any]) -> dict[str, Any] | None:
    """RiskAssessment for the served forecast, or None when there is no usable forecast."""
    if fc is None or fc.status != "ok" or fc.excursion is None:
        return None
    ex = fc.excursion
    issued = _iso(fc.issued_at)
    end = fc.issued_at + timedelta(minutes=ex.horizon_min)
    preds: list[dict[str, Any]] = [{
        "outcome": {"text": f"Hyperglycaemic excursion: {ex.event_definition}"},
        "probabilityDecimal": round(float(ex.probability), 3),
        "whenPeriod": {"start": issued, "end": _iso(end)},
        "rationale": (f"Model-estimated probability from research model {fc.model_version} (alert threshold "
                      f"{ex.alert_threshold:.2f}, alert {'on' if ex.alert else 'off'}). Trained and evaluated on synthetic "
                      "data only; not clinically calibrated."),
    }]
    lows = [p for p in fc.trajectory if p.lower_mg_dl < LOW_GLUCOSE_MG_DL]
    if lows:
        lowest = min(lows, key=lambda p: p.lower_mg_dl)
        meds = [f"{m.name} ({HYPO_DRUG_CLASSES[str(getattr(m.drug_class, 'value', m.drug_class))]})"
                for m in record.medications if str(getattr(m.drug_class, "value", m.drug_class)) in HYPO_DRUG_CLASSES]
        preds.append({
            "outcome": {"text": "Low-glucose watch: lower edge of the 80% prediction interval below 70 mg/dL"},
            "whenPeriod": {"start": _iso(lows[0].timestamp), "end": _iso(fc.trajectory[-1].timestamp)},
            "rationale": (f"Qualitative flag, NOT a probability of hypoglycaemia. Lower bound first below 70 mg/dL at "
                          f"+{lows[0].horizon_min} min (lowest {lowest.lower_mg_dl:.0f} mg/dL at +{lowest.horizon_min} min). "
                          + (f"Record lists glucose-lowering medication that can cause hypoglycaemia: {', '.join(meds)}."
                             if meds else "No sulfonylurea or insulin on the record.")),
        })
    return {
        "resourceType": "RiskAssessment", "meta": _meta(), "status": "final", "subject": subject,
        "occurrenceDateTime": issued,
        "method": {"text": "GlucoTwin research forecast (synthetic-data model; not a medical device)"},
        "prediction": preds,
        "note": [{"text": DISCLAIMER}],
    }


def patient_bundle(record: PatientRecord, cgm: Iterable[tuple[datetime, float]],
                   forecast: Forecast | None = None) -> dict[str, Any]:
    """Build the Bundle as a JSON-ready dict. ``cgm`` holds (timestamp, mg/dL) readings the twin has received;
    ``forecast`` (optional) is the twin's latest served forecast, exported as a RiskAssessment."""
    pid = record.patient_id
    patient_ref = _uid(pid, "patient")
    subject = {"reference": patient_ref, "display": record.display_name}
    entries: list[dict[str, Any]] = [{"fullUrl": patient_ref, "resource": {
        "resourceType": "Patient", "meta": _meta(),
        "identifier": [{"system": f"{REPO_URL}/patient-id", "value": pid}],
        "active": True, "name": [{"text": record.display_name}], "gender": record.sex.value,
    }}]
    for name in record.conditions:
        cond: dict[str, Any] = {
            "resourceType": "Condition", "meta": _meta(),
            "clinicalStatus": {"coding": [_coding(COND_CLINICAL, "active", "Active")]},
            "category": [{"coding": [_coding(COND_CATEGORY, "problem-list-item", "Problem List Item")]}],
            "code": {"text": name}, "subject": subject,
        }
        if name in CONDITION_CODES:
            cond["code"]["coding"] = [_coding(SNOMED, *CONDITION_CODES[name])]
        entries.append({"fullUrl": _uid(pid, f"condition/{name}"), "resource": cond})
    for med in record.medications:
        concept: dict[str, Any] = {"text": med.name}
        if med.name in RXNORM_CODES:
            concept["coding"] = [_coding(RXNORM, *RXNORM_CODES[med.name])]
        stmt: dict[str, Any] = {"resourceType": "MedicationStatement", "meta": _meta(), "status": "active",
                                "medicationCodeableConcept": concept, "subject": subject}
        if med.dose:
            stmt["dosage"] = [{"text": med.dose}]
        entries.append({"fullUrl": _uid(pid, f"medication/{med.name}"), "resource": stmt})
    times: list[datetime] = []
    for lab in record.labs:
        code: dict[str, Any] = {"text": lab.name}
        if lab.name in LAB_CODES:
            code["coding"] = [_coding(LOINC, *LAB_CODES[lab.name])]
        times.append(lab.measured_at)
        entries.append({"fullUrl": _uid(pid, f"lab/{lab.name}/{_iso(lab.measured_at)}"), "resource": {
            "resourceType": "Observation", "meta": _meta(), "status": "final",
            "category": [{"coding": [_coding(OBS_CATEGORY, "laboratory", "Laboratory")]}],
            "code": code, "subject": subject, "effectiveDateTime": _iso(lab.measured_at),
            "valueQuantity": _quantity(lab.value, lab.unit),
        }})
    for ts, value in cgm:
        times.append(ts)
        entries.append({"fullUrl": _uid(pid, f"cgm/{_iso(ts)}"), "resource": {
            "resourceType": "Observation", "meta": _meta(), "status": "final",
            "category": [{"coding": [_coding(OBS_CATEGORY, "laboratory", "Laboratory")]}],
            "code": {"coding": [_coding(LOINC, *CGM_CODE)], "text": "CGM glucose (synthetic)"},
            "subject": subject, "effectiveDateTime": _iso(ts), "valueQuantity": _quantity(round(value, 1), "mg/dL"),
        }})
    risk = _risk_assessment(record, forecast, subject)
    if risk is not None:
        times.append(forecast.issued_at)
        entries.append({"fullUrl": _uid(pid, f"risk/{_iso(forecast.issued_at)}"), "resource": risk})
    bundle: dict[str, Any] = {
        "resourceType": "Bundle", "id": f"glucotwin-{pid.lower()}", "meta": _meta(), "type": "collection",
        "entry": entries,
    }
    if times:
        bundle["timestamp"] = _iso(max(times))
    return bundle
